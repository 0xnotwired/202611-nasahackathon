// Shared fixtures for the F2 view tests and the G2 walkthrough: the synthetic scenario in a memory store, with the services a view receives.
import {generateScenario} from '../../app/scenario/index.js';
import {openStore} from '../../app/store/index.js';
import * as readings from '../../app/readings/index.js';
import * as catalogs from '../../app/catalogs/index.js';
import * as core from '../../app/core/index.js';
import * as plan from '../../app/plan/index.js';
import * as procedures from '../../app/procedures/index.js';

export const NOW = '2026-11-15T18:00:00.000Z';
export const scenario = generateScenario({seed: 1});
export const SUBJECT = scenario.records[0].subject;
export const DAY = n => `2026-11-${String(n).padStart(2, '0')}`;
let counter = 0;

/** A valid synthetic schema2 record; override any field. Absent states carry no value or unit. */
export function makeRecord(fields = {}) {
  const base = {id: `fx-${++counter}`, schema_version: 2, type: 'measurement', state: 'recorded', variable: 'pulse', value: 70, unit: 'bpm', method: 'demo-device', time: `${DAY(15)}T10:00:00.000Z`,
    origin: 'synthetic', source: 'user_entered', mission_phase: 'mission', subject: SUBJECT, ...fields};
  if (base.state !== 'recorded') { delete base.value; if (!Object.hasOwn(fields, 'unit')) delete base.unit; }
  if (Object.hasOwn(fields, 'value') && fields.value === undefined) { delete base.value; if (!Object.hasOwn(fields, 'unit')) delete base.unit; } // an action or observation without a number
  return base;
}

/** Services as a view receives them. `records` are added to the scenario's; `without` removes scenario records by predicate. */
export async function makeServices({records = [], objects = {}, without = () => false, writable = true, config = scenario.config[0], plan: planOverride, flags = {}, drop = [], procedureList = scenario.procedures} = {}) {
  const opened = await openStore({kind: 'memory', name: 'fixture'});
  const store = opened.value;
  const saved = await store.saveBatch('records', [...scenario.records.filter(record => !without(record)), ...records]);
  if (!saved.ok) throw new Error(`fixture records refused: ${JSON.stringify(saved.error)}`);
  for (const [collection, items] of Object.entries(objects)) { const r = await store.saveBatch(collection, items); if (!r.ok) throw new Error(`fixture ${collection} refused: ${JSON.stringify(r.error)}`); }
  let ids = 0;
  const services = {store, readings, catalogs, core, plan: planOverride ?? plan, procedures, procedure_list: procedureList, subject: SUBJECT, clock: () => NOW, newId: () => `new-${++ids}`, config,
    data_source: {id: 'demo', label: 'Synthetic demo (fictional data)', synthetic: true, note: 'Fictional records generated by the team.'}, writable, record_origin: 'synthetic', flags};
  for (const key of drop) delete services[key];
  return services;
}
